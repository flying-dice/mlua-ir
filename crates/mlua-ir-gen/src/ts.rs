//! IR → TypeScript declarations for a backend compiled to Luau by TypeScriptToLua.
//!
//! A function that takes `this: void` is called with `.`, a method with `:`. Multiple returns are TSTL's
//! `LuaMultiReturn`; a fallible call is a union of tuples, so destructuring and checking the error narrows the value.

use std::fmt::Write;

use mlua_ir::ir::{Field, Function, Ir, Module, ModuleKind, Param, Returns, Ty, TypeBody, TypeDef};

use crate::common::{function_doc, is_identifier, module_type, owned_types, quoted, shown};

const PRELUDE: &str = "\
/// <reference types=\"@typescript-to-lua/language-extensions\" />

/** A stream of `T` that may end in an error `E` (`mlua_ir::Stream<T, E>`). */
interface mlua_Stream<T, E> {
  /** The next item: `[item, undefined]`, `[undefined, error]`, or `[undefined, undefined]` at the end. */
  next(): LuaMultiReturn<[T, undefined] | [undefined, E] | [undefined, undefined]>
  /** An iterator over the items for a `for...of` loop: the stream's error is raised. */
  items(): LuaIterable<T>
  /** Stops reading: later `next` calls return `[undefined, undefined]`. */
  close(): void
}
";

/// Words TypeScript does not take as a declaration's name.
const RESERVED: [&str; 45] = [
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
    "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
    "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with",
    "implements", "interface", "let", "package", "private", "protected", "public", "static", "yield",
];

pub fn file(ir: &Ir) -> String {
    let mut out = format!("// GENERATED by mlua-ir-gen from the schema of runtime {}. Do not edit.\n\n{PRELUDE}", ir.version);
    for module in &ir.modules {
        out.push('\n');
        out.push_str(&module_section(ir, module));
    }
    out
}

pub fn module_section(ir: &Ir, module: &Module) -> String {
    let mut out = format!("// ===== {} =====\n\n", module.name);
    let owned = owned_types(ir, module);
    for def in &owned {
        out.push_str(&type_def(def));
        out.push('\n');
    }
    match module.kind {
        ModuleKind::Require => {
            doc(&mut out, module.doc.as_deref(), "");
            let _ = writeln!(out, "declare module {} {{", quoted(&module.name));
            // A member named by a word TypeScript reserves (`var`) is declared under another name and exported
            // under its own: `env.var(...)` still reads as it does in Lua.
            let mut renamed: Vec<&str> = Vec::new();
            let local = |name: &str| -> (String, &'static str) {
                if RESERVED.contains(&name) {
                    (format!("{name}_"), "")
                } else {
                    (name.to_owned(), "export ")
                }
            };
            for c in &module.constants {
                doc(&mut out, c.doc.as_deref(), "  ");
                let (name, export) = local(&c.name);
                if export.is_empty() {
                    renamed.push(&c.name);
                }
                let _ = writeln!(out, "  {export}const {name}: {}", ty(&c.ty));
            }
            for o in &module.objects {
                let _ = writeln!(out, "  export const {}: {}Statics", o.name, o.type_name);
            }
            for f in &module.functions {
                doc(&mut out, function_doc(f, throws(f)).as_deref(), "  ");
                let (name, export) = local(&f.name);
                if export.is_empty() {
                    renamed.push(&f.name);
                }
                let _ = writeln!(out, "  {export}function {name}(this: void{}): {}", params(&f.params, true), returns(&f.returns));
            }
            for name in renamed {
                let _ = writeln!(out, "  export {{ {name}_ as {name} }}");
            }
            for def in &owned {
                let _ = writeln!(out, "  export type {} = {}", def.short_name, def.name);
            }
            out.push_str("}\n");
            let _ = module_type(module);
        }
        ModuleKind::Globals => {
            for c in &module.constants {
                doc(&mut out, c.doc.as_deref(), "");
                let _ = writeln!(out, "declare const {}: {}", c.name, ty(&c.ty));
            }
            for f in &module.functions {
                doc(&mut out, function_doc(f, throws(f)).as_deref(), "");
                let _ = writeln!(out, "declare function {}(this: void{}): {}", f.name, params(&f.params, true), returns(&f.returns));
            }
        }
    }
    out
}

fn throws(f: &Function) -> Option<String> {
    f.raises.as_ref().map(|t| format!("@throws {{{}}} when it fails; `pcall` catches it.", ty(t)))
}

fn doc(out: &mut String, text: Option<&str>, indent: &str) {
    let Some(text) = text else { return };
    let lines: Vec<&str> = text.lines().collect();
    if lines.len() == 1 {
        let _ = writeln!(out, "{indent}/** {} */", lines[0]);
    } else {
        let _ = writeln!(out, "{indent}/**");
        for line in lines {
            let _ = if line.is_empty() { writeln!(out, "{indent} *") } else { writeln!(out, "{indent} * {line}") };
        }
        let _ = writeln!(out, "{indent} */");
    }
}

fn prop(name: &str) -> String {
    if is_identifier(name) { name.to_owned() } else { quoted(name) }
}

fn method_name(name: &str) -> String {
    // `new(...)` in an interface is a construct signature; quoted, it is a method.
    if name == "new" || !is_identifier(name) { quoted(name) } else { name.to_owned() }
}

pub fn type_def(def: &TypeDef) -> String {
    let mut out = String::new();
    let name = &def.name;
    match &def.body {
        TypeBody::Record { fields } | TypeBody::Options { fields } => {
            let options = matches!(def.body, TypeBody::Options { .. });
            doc(&mut out, def.doc.as_deref(), "");
            let _ = writeln!(out, "interface {name} {{");
            for f in fields {
                doc(&mut out, field_doc(f).as_deref(), "  ");
                let _ = writeln!(out, "  {}", field(f, options));
            }
            out.push_str("}\n");
        }
        TypeBody::StringEnum { variants } => {
            let mut text = def.doc.clone().unwrap_or_default();
            for v in variants.iter().filter(|v| v.doc.is_some()) {
                let _ = write!(text, "\n- `{}`: {}", v.value, v.doc.as_deref().unwrap_or_default());
            }
            doc(&mut out, Some(text.trim()).filter(|t| !t.is_empty()), "");
            let members: Vec<String> = variants.iter().map(|v| quoted(&v.value)).collect();
            let _ = writeln!(out, "type {name} = {}", members.join(" | "));
        }
        TypeBody::TaggedUnion { tag, variants } | TypeBody::Error { tag, variants, .. } => {
            let common: &[Field] = match &def.body {
                TypeBody::Error { common, .. } => common,
                _ => &[],
            };
            if matches!(def.body, TypeBody::Error { .. }) {
                let kinds: Vec<String> = variants.iter().map(|v| quoted(&v.tag_value)).collect();
                let _ = writeln!(out, "/** The kinds of `{name}`. */\ntype {name}Kind = {}\n", kinds.join(" | "));
            }
            doc(&mut out, def.doc.as_deref(), "");
            let _ = writeln!(out, "type {name} =");
            for v in variants {
                doc(&mut out, v.doc.as_deref(), "  ");
                let mut parts = vec![format!("{}: {}", prop(tag), quoted(&v.tag_value))];
                parts.extend(v.fields.iter().chain(common).map(|f| field(f, false)));
                let _ = writeln!(out, "  | {{ {} }}", parts.join("; "));
            }
        }
        TypeBody::Object { fields, methods, statics } => {
            doc(&mut out, def.doc.as_deref(), "");
            let _ = writeln!(out, "interface {name} {{");
            for f in fields {
                doc(&mut out, f.doc.as_deref(), "  ");
                let _ = writeln!(out, "  {}", field(f, false));
            }
            for m in methods {
                doc(&mut out, function_doc(m, throws(m)).as_deref(), "  ");
                let _ = writeln!(out, "  {}({}): {}", method_name(&m.name), params(&m.params, false), returns(&m.returns));
            }
            out.push_str("}\n");
            if !statics.is_empty() {
                let _ = writeln!(out, "\n/** The statics of `{name}`. */\ninterface {name}Statics {{");
                for s in statics {
                    doc(&mut out, function_doc(s, throws(s)).as_deref(), "  ");
                    let _ = writeln!(out, "  {}(this: void{}): {}", method_name(&s.name), params(&s.params, true), returns(&s.returns));
                }
                out.push_str("}\n");
            }
        }
        TypeBody::Alias { ty: inner } => {
            doc(&mut out, def.doc.as_deref(), "");
            let _ = writeln!(out, "type {name} = {}", ty(inner));
        }
    }
    out
}

fn field_doc(f: &Field) -> Option<String> {
    let default = f.default.as_ref().map(|d| format!("@default {}", shown(d)));
    match (f.doc.clone(), default) {
        (Some(d), Some(x)) => Some(format!("{d} {x}")),
        (d, x) => d.or(x),
    }
}

fn field(f: &Field, all_optional: bool) -> String {
    let readonly = if f.readonly { "readonly " } else { "" };
    match &f.ty {
        Ty::Optional { inner } => format!("{readonly}{}?: {}", prop(&f.name), ty(inner)),
        t if all_optional => format!("{readonly}{}?: {}", prop(&f.name), ty(t)),
        t => format!("{readonly}{}: {}", prop(&f.name), ty(t)),
    }
}

fn wrapped(t: &Ty) -> String {
    match t {
        Ty::Union { .. } | Ty::Function { .. } | Ty::Optional { .. } => format!("({})", ty(t)),
        _ => ty(t),
    }
}

pub fn ty(t: &Ty) -> String {
    match t {
        Ty::Nil => "undefined".into(),
        Ty::Boolean => "boolean".into(),
        Ty::Integer { .. } | Ty::Number => "number".into(),
        Ty::String => "string".into(),
        Ty::Unknown { .. } => "unknown".into(),
        Ty::Optional { inner } => format!("{} | undefined", wrapped(inner)),
        Ty::List { item } => format!("{}[]", wrapped(item)),
        Ty::Map { key, value } => {
            let k = if matches!(**key, Ty::Integer { .. } | Ty::Number) { "number" } else { "string" };
            format!("{{ [key: {k}]: {} }}", ty(value))
        }
        Ty::Literal { value } => quoted(value),
        Ty::Union { members } => members.iter().map(wrapped).collect::<Vec<_>>().join(" | "),
        Ty::Named { name } => name.clone(),
        Ty::Function { params: p, returns: r } => format!("(this: void{}) => {}", params(p, true), returns(r)),
        Ty::Stream { item, error } => format!("mlua_Stream<{}, {}>", ty(item), ty(error)),
    }
}

fn param(p: &Param) -> String {
    if p.variadic {
        return format!("...{}: {}[]", p.name, wrapped(&p.ty));
    }
    match (&p.ty, p.optional) {
        (Ty::Optional { inner }, true) => format!("{}?: {}", p.name, ty(inner)),
        (t, true) => format!("{}?: {}", p.name, ty(t)),
        (t, false) => format!("{}: {}", p.name, ty(t)),
    }
}

/// The parameters; `after_this` puts a `, ` before them (they follow `this: void`).
fn params(ps: &[Param], after_this: bool) -> String {
    let joined = ps.iter().map(param).collect::<Vec<_>>().join(", ");
    if after_this && !joined.is_empty() { format!(", {joined}") } else { joined }
}

pub fn returns(r: &Returns) -> String {
    match r {
        Returns::None => "void".into(),
        Returns::One { ty: t } => ty(t),
        Returns::Many { tys } => format!("LuaMultiReturn<[{}]>", tys.iter().map(ty).collect::<Vec<_>>().join(", ")),
        Returns::Fallible { ok, err } => format!("LuaMultiReturn<[{}, undefined] | [undefined, {}]>", ty(ok), ty(err)),
    }
}
