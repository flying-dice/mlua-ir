//! IR → a Luau definitions file for luau-lsp (`--definitions:@mlua=<file>`).

use std::fmt::Write;

use mlua_ir::ir::{Field, Function, Ir, Module, ModuleKind, Param, Returns, Ty, TypeBody, TypeDef};

use crate::common::{function_doc, is_identifier, is_optional, module_type, owned_types, quoted, shown};

const KEYWORDS: [&str; 22] = [
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil", "not", "or",
    "repeat", "return", "then", "true", "until", "while", "continue",
];

const PRELUDE: &str = "\
--- A stream of `T` that may end in an error `E` (`mlua_ir::Stream<T, E>`).
export type mlua_Stream<T, E> = {
\t--- The next item: `(item, nil)`, `(nil, error)`, or `(nil, nil)` at the end. Yields while it waits.
\tnext: (self: mlua_Stream<T, E>) -> (T?, E?),
\t--- An iterator over the items for a `for` loop: the stream's error is raised.
\titems: (self: mlua_Stream<T, E>) -> () -> T?,
\t--- Stops reading: later `next` calls return `(nil, nil)`.
\tclose: (self: mlua_Stream<T, E>) -> (),
}
";

/// The whole definitions file.
pub fn file(ir: &Ir) -> String {
    let mut out = format!(
        "-- GENERATED by mlua-ir-gen from the schema of runtime {}. Do not edit.\n\n{PRELUDE}",
        ir.version
    );
    for module in &ir.modules {
        out.push('\n');
        out.push_str(&module_section(ir, module));
    }
    let requires: Vec<String> = ir
        .modules
        .iter()
        .filter(|m| m.kind == ModuleKind::Require)
        .map(|m| format!("((path: {}) -> {})", quoted(&m.name), module_type(m)))
        .collect();
    if !requires.is_empty() {
        let _ = write!(out, "\ndeclare require: {}\n", requires.join("\n\t& "));
    }
    out
}

/// One module's declarations: its types, then the module (or the globals).
pub fn module_section(ir: &Ir, module: &Module) -> String {
    let mut out = format!("-- ===== {} =====\n\n", module.name);
    for def in owned_types(ir, module) {
        out.push_str(&type_def(def));
        out.push('\n');
    }
    match module.kind {
        ModuleKind::Require => {
            doc(&mut out, module.doc.as_deref(), "");
            let _ = writeln!(out, "export type {} = {{", module_type(module));
            for c in &module.constants {
                doc(&mut out, c.doc.as_deref(), "\t");
                let _ = writeln!(out, "\t{}: {},", key(&c.name), ty(&c.ty));
            }
            for o in &module.objects {
                let _ = writeln!(out, "\t{}: {}Statics,", key(&o.name), o.type_name);
            }
            for f in &module.functions {
                doc(&mut out, function_doc(f, raises(f)).as_deref(), "\t");
                let _ = writeln!(out, "\t{}: {},", key(&f.name), function_type(&f.params, &f.returns, None));
            }
            out.push_str("}\n");
        }
        ModuleKind::Globals => {
            for c in &module.constants {
                doc(&mut out, c.doc.as_deref(), "");
                let _ = writeln!(out, "declare {}: {}", c.name, ty(&c.ty));
            }
            for f in &module.functions {
                doc(&mut out, function_doc(f, raises(f)).as_deref(), "");
                let _ = writeln!(out, "declare function {}({}): {}", f.name, params(&f.params), returns(&f.returns));
            }
        }
    }
    out
}

fn raises(f: &Function) -> Option<String> {
    f.raises.as_ref().map(|t| format!("Raises `{}` when it fails; `pcall` catches it.", ty(t)))
}

fn doc(out: &mut String, text: Option<&str>, indent: &str) {
    if let Some(text) = text {
        for line in text.lines() {
            let _ = if line.is_empty() { writeln!(out, "{indent}---") } else { writeln!(out, "{indent}--- {line}") };
        }
    }
}

fn key(name: &str) -> String {
    if is_identifier(name) && !KEYWORDS.contains(&name) { name.to_owned() } else { format!("[{}]", quoted(name)) }
}

pub fn type_def(def: &TypeDef) -> String {
    let mut out = String::new();
    let name = &def.name;
    match &def.body {
        TypeBody::Record { fields } => {
            doc(&mut out, def.doc.as_deref(), "");
            let _ = writeln!(out, "export type {name} = {}", table(fields, "", false));
        }
        TypeBody::Options { fields } => {
            doc(&mut out, def.doc.as_deref(), "");
            let _ = writeln!(out, "export type {name} = {}", table(fields, "", true));
        }
        TypeBody::StringEnum { variants } => {
            let mut text = def.doc.clone().unwrap_or_default();
            for v in variants.iter().filter(|v| v.doc.is_some()) {
                let _ = write!(text, "\n- `{}`: {}", v.value, v.doc.as_deref().unwrap_or_default());
            }
            doc(&mut out, Some(text.trim()).filter(|t| !t.is_empty()), "");
            let members: Vec<String> = variants.iter().map(|v| quoted(&v.value)).collect();
            let _ = writeln!(out, "export type {name} = {}", members.join(" | "));
        }
        TypeBody::TaggedUnion { tag, variants } | TypeBody::Error { tag, variants, .. } => {
            let common: &[Field] = match &def.body {
                TypeBody::Error { common, .. } => common,
                _ => &[],
            };
            if matches!(def.body, TypeBody::Error { .. }) {
                let kinds: Vec<String> = variants.iter().map(|v| quoted(&v.tag_value)).collect();
                let _ = writeln!(out, "--- The kinds of `{name}`.\nexport type {name}Kind = {}\n", kinds.join(" | "));
            }
            doc(&mut out, def.doc.as_deref(), "");
            let _ = writeln!(out, "export type {name} =");
            for (i, v) in variants.iter().enumerate() {
                doc(&mut out, v.doc.as_deref(), "\t");
                let mut fields = vec![Field {
                    name: tag.clone(),
                    doc: None,
                    ty: Ty::Literal { value: v.tag_value.clone() },
                    default: None,
                    readonly: false,
                }];
                fields.extend(v.fields.iter().cloned());
                fields.extend(common.iter().cloned());
                let _ = writeln!(out, "\t{}{}", if i == 0 { "" } else { "| " }, inline_table(&fields));
            }
        }
        TypeBody::Object { fields, methods, statics } => {
            doc(&mut out, def.doc.as_deref(), "");
            let _ = writeln!(out, "export type {name} = {{");
            for f in fields {
                doc(&mut out, Some(&with_readonly(f)), "\t");
                let _ = writeln!(out, "\t{}: {},", key(&f.name), ty(&f.ty));
            }
            for m in methods {
                doc(&mut out, function_doc(m, raises(m)).as_deref(), "\t");
                let _ = writeln!(out, "\t{}: {},", key(&m.name), function_type(&m.params, &m.returns, Some(name)));
            }
            out.push_str("}\n");
            if !statics.is_empty() {
                let _ = writeln!(out, "\n--- The statics of `{name}`.\nexport type {name}Statics = {{");
                for s in statics {
                    doc(&mut out, function_doc(s, raises(s)).as_deref(), "\t");
                    let _ = writeln!(out, "\t{}: {},", key(&s.name), function_type(&s.params, &s.returns, None));
                }
                out.push_str("}\n");
            }
        }
        TypeBody::Alias { ty: inner } => {
            doc(&mut out, def.doc.as_deref(), "");
            let _ = writeln!(out, "export type {name} = {}", ty(inner));
        }
    }
    out
}

fn with_readonly(f: &Field) -> String {
    match &f.doc {
        Some(d) => format!("{d} Read-only."),
        None => "Read-only.".to_owned(),
    }
}

fn field_doc(f: &Field) -> Option<String> {
    let default = f.default.as_ref().map(|d| format!("Default: `{}`.", shown(d)));
    match (f.doc.clone(), default) {
        (Some(d), Some(x)) => Some(format!("{d} {x}")),
        (d, x) => d.or(x),
    }
}

fn table(fields: &[Field], indent: &str, all_optional: bool) -> String {
    if fields.is_empty() {
        return "{}".to_owned();
    }
    let mut out = String::from("{\n");
    for f in fields {
        doc(&mut out, field_doc(f).as_deref(), &format!("{indent}\t"));
        let t = if all_optional && !is_optional(&f.ty) { format!("{}?", ty(&f.ty)) } else { ty(&f.ty) };
        let _ = writeln!(out, "{indent}\t{}: {t},", key(&f.name));
    }
    let _ = write!(out, "{indent}}}");
    out
}

fn inline_table(fields: &[Field]) -> String {
    let parts: Vec<String> = fields.iter().map(|f| format!("{}: {}", key(&f.name), ty(&f.ty))).collect();
    format!("{{ {} }}", parts.join(", "))
}

/// A type in a position.
pub fn ty(t: &Ty) -> String {
    match t {
        Ty::Nil => "nil".into(),
        Ty::Boolean => "boolean".into(),
        Ty::Integer { .. } | Ty::Number => "number".into(),
        Ty::String => "string".into(),
        Ty::Unknown { .. } => "unknown".into(),
        Ty::Optional { inner } => match **inner {
            Ty::Union { .. } | Ty::Function { .. } => format!("({})?", ty(inner)),
            _ => format!("{}?", ty(inner)),
        },
        Ty::List { item } => format!("{{ {} }}", ty(item)),
        Ty::Map { key: k, value } => format!("{{ [{}]: {} }}", ty(k), ty(value)),
        Ty::Literal { value } => quoted(value),
        Ty::Union { members } => members
            .iter()
            .map(|m| if matches!(m, Ty::Function { .. }) { format!("({})", ty(m)) } else { ty(m) })
            .collect::<Vec<_>>()
            .join(" | "),
        Ty::Named { name } => name.clone(),
        Ty::Function { params: p, returns: r } => function_type(p, r, None),
        Ty::Stream { item, error } => format!("mlua_Stream<{}, {}>", ty(item), ty(error)),
    }
}

fn param(p: &Param) -> String {
    let t = ty(&p.ty);
    if p.optional && !is_optional(&p.ty) { format!("{}: {t}?", p.name) } else { format!("{}: {t}", p.name) }
}

fn params(ps: &[Param]) -> String {
    ps.iter().map(param).collect::<Vec<_>>().join(", ")
}

fn function_type(ps: &[Param], r: &Returns, self_ty: Option<&str>) -> String {
    let mut all: Vec<String> = self_ty.map(|s| format!("self: {s}")).into_iter().collect();
    all.extend(ps.iter().map(param));
    format!("({}) -> {}", all.join(", "), returns(r))
}

fn optional(t: &Ty) -> String {
    if is_optional(t) { ty(t) } else { ty(&Ty::optional(t.clone())) }
}

pub fn returns(r: &Returns) -> String {
    match r {
        Returns::None => "()".into(),
        Returns::One { ty: t @ Ty::Function { .. } } => format!("({})", ty(t)),
        Returns::One { ty: t } => ty(t),
        Returns::Many { tys } => format!("({})", tys.iter().map(ty).collect::<Vec<_>>().join(", ")),
        Returns::Fallible { ok, err } => format!("({}, {})", optional(ok), optional(err)),
    }
}
